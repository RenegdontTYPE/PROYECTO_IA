print("Cargando CSV y optimizando memoria...")
# Leer el archivo (asegúrate de que el nombre coincida exactamente con el que subiste)
df = pd.read_csv("Friday-WorkingHours-Afternoon-PortScan.pcap_ISCX.csv")

