import torch
import torch.nn as nn
import torch.optim as optim
import json

# Filtrar SOLO el tráfico normal (BENIGN = 0) del set de entrenamiento
X_train_benign = X_train[y_train == 0]

# Convertir a tensores de PyTorch
tensor_X_train_normal = torch.tensor(X_train_benign, dtype=torch.float32)
tensor_X_test = torch.tensor(X_test, dtype=torch.float32) # Test tiene de todo para evaluar

# Definir la arquitectura de compresión y descompresión
class Autoencoder(nn.Module):
    def __init__(self, input_dim):
        super(Autoencoder, self).__init__()
        # Encoder: Comprime las 15 características
        self.encoder = nn.Sequential(
            nn.Linear(input_dim, 12),
            nn.ReLU(True),
            nn.Linear(12, 8),
            nn.ReLU(True)
        )
        # Decoder: Intenta reconstruirlas
        self.decoder = nn.Sequential(
            nn.Linear(8, 12),
            nn.ReLU(True),
            nn.Linear(12, input_dim)
        )

    def forward(self, x):
        x = self.encoder(x)
        x = self.decoder(x)
        return x

input_dim = X_train.shape[1]
modelo_ae = Autoencoder(input_dim)
print(modelo_ae)

print("Entrenando el Autoencoder solo con tráfico normal...")
criterion = nn.MSELoss()
optimizer = optim.Adam(modelo_ae.parameters(), lr=0.005)
epochs = 50
batch_size = 256

# DataLoader básico
dataset = torch.utils.data.TensorDataset(tensor_X_train_normal, tensor_X_train_normal)
dataloader = torch.utils.data.DataLoader(dataset, batch_size=batch_size, shuffle=True)

modelo_ae.train()
for epoch in range(epochs):
    loss_total = 0
    for data in dataloader:
        inputs, _ = data
        optimizer.zero_grad()
        outputs = modelo_ae(inputs)
        loss = criterion(outputs, inputs)
        loss.backward()
        optimizer.step()
        loss_total += loss.item()

    if (epoch + 1) % 10 == 0:
        print(f'Epoch [{epoch+1}/{epochs}], Loss/Error de Reconstrucción: {loss_total/len(dataloader):.6f}')

print("Calculando umbral de anomalías y guardando el modelo...")
modelo_ae.eval()

# 1. Calcular el error (MSE) de reconstrucción del tráfico NORMAL
with torch.no_grad():
    reconstruccion_normal = modelo_ae(tensor_X_train_normal)
    mse_normal = torch.mean((tensor_X_train_normal - reconstruccion_normal)**2, dim=1).numpy()

# 2. Definir el umbral (Promedio del error normal + 3 desviaciones estándar)
umbral = float(np.mean(mse_normal) + 3 * np.std(mse_normal))
print(f"Umbral de anomalía definido en: {umbral:.6f}")

# 3. Evaluar con el set de prueba (que tiene ataques)
with torch.no_grad():
    reconstruccion_test = modelo_ae(tensor_X_test)
    mse_test = torch.mean((tensor_X_test - reconstruccion_test)**2, dim=1).numpy()

# Si el error supera el umbral, es anomalía (1), si no, normal (0)
predicciones_ae = (mse_test > umbral).astype(int)

print("\n--- Resultados Autoencoder (Detección de Anomalías) ---")
# Comparamos con y_test (sabiendo que 0 es normal y 1 es PortScan)
print(classification_report(y_test, predicciones_ae, target_names=['Normal', 'Anomalía']))

# 4. Guardar los pesos del modelo PyTorch y el umbral exacto
torch.save(modelo_ae.state_dict(), 'autoencoder.pth')

with open('umbral.json', 'w') as f:
    json.dump({'umbral_mse': umbral, 'caracteristicas': features_clave}, f)

