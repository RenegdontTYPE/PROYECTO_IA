# 2. Calcular métricas exactas que pide el profesor
def calcular_metricas(y_real, y_pred, modelo_nombre):
    tn, fp, fn, tp = confusion_matrix(y_real, y_pred).ravel()
    return {
        "modelo": modelo_nombre,
        "precision": round(precision_score(y_real, y_pred, zero_division=0), 4),
        "recall": round(recall_score(y_real, y_pred, zero_division=0), 4),
        "f1_score": round(f1_score(y_real, y_pred, zero_division=0), 4),
        "tasa_falsos_positivos_FPR": round(fp / (fp + tn), 4) if (fp + tn) > 0 else 0.0
    }

metricas_rf = calcular_metricas(y_test, rf_preds, "Random Forest")
